// Conversions for the color picker of the theme editor: themes store #rrggbb, people pick in HSL.

export interface Hsl {
  h: number; // 0–359
  s: number; // 0–100
  l: number; // 0–100
}

/** #rrggbb from #rgb, #rrggbb or the same without #; undefined for anything else. */
export function normalizeHex(text: string): string | undefined {
  const value = text.trim().toLowerCase().replace(/^#/, '');
  if (/^[0-9a-f]{3}$/.test(value)) {
    return `#${[...value].map((c) => c + c).join('')}`;
  }
  return /^[0-9a-f]{6}$/.test(value) ? `#${value}` : undefined;
}

export function hexToHsl(hex: string): Hsl {
  const [r = 0, g = 0, b = 0] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  const d = max - min;
  let h = 0;
  let s = 0;
  if (d > 0) {
    s = d / (1 - Math.abs(2 * l - 1));
    if (max === r) {
      h = ((g - b) / d) % 6;
    } else if (max === g) {
      h = (b - r) / d + 2;
    } else {
      h = (r - g) / d + 4;
    }
    h = (h * 60 + 360) % 360;
  }
  return { h: Math.round(h) % 360, s: Math.round(s * 100), l: Math.round(l * 100) };
}

export function hslToHex({ h, s, l }: Hsl): string {
  const sat = s / 100;
  const light = l / 100;
  const c = (1 - Math.abs(2 * light - 1)) * sat;
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = light - c / 2;
  const [r, g, b] =
    h < 60
      ? [c, x, 0]
      : h < 120
        ? [x, c, 0]
        : h < 180
          ? [0, c, x]
          : h < 240
            ? [0, x, c]
            : h < 300
              ? [x, 0, c]
              : [c, 0, x];
  return `#${[r, g, b]
    .map((v) =>
      Math.round((v + m) * 255)
        .toString(16)
        .padStart(2, '0'),
    )
    .join('')}`;
}
